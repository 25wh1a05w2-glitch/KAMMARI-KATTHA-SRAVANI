import numpy as np
import matplotlib.pyplot as plt

tri = np.array([[0, 1, 0.5],
                [0, 0, 1.0]])

# Function to close the triangle
def close_loop(points):
    return np.hstack([points, points[:, :1]])

# 1. Scaling matrix (x*2, y*0.5)
S = np.array([[2., 0.],
              [0., 0.5]])

# 2. Rotation matrix (45 degrees)
theta = np.radians(45)

R = np.array([[np.cos(theta), -np.sin(theta)],
              [np.sin(theta),  np.cos(theta)]])

# 3. Apply scaling first, then rotation
scaled_tri = S @ tri
transformed_tri = R @ scaled_tri

# Close the triangles for plotting
original = close_loop(tri)
transformed = close_loop(transformed_tri)

# Plot original vs transformed
plt.plot(original[0], original[1], marker='o', label='Original')
plt.plot(transformed[0], transformed[1], marker='o', label='Transformed')

plt.xlabel('X')
plt.ylabel('Y')
plt.title('Original vs Transformed Triangle')
plt.axis('equal')
plt.grid(True)
plt.legend()
plt.show()

