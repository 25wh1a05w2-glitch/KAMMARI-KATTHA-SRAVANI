    # 1. L1 and L2 norm of u
    l1 = np.linalg.norm(u, ord=1)
    l2 = np.linalg.norm(u, ord=2)

    # 2. Cosine similarity of u and v
    similarity = cosine(u, v)

    print("Pair", i)
    print("L1 norm:", l1)
    print("L2 norm:", l2)
    print("Cosine similarity:", similarity)
